export function getBusinessWorkingHours(business: Business): WorkingHoursDetails {
  if (business.workingHoursDetails) {
    return business.workingHoursDetails;
  }

  const rawHours = business.workingHours;

  return {
    weekdays: rawHours ? `Понеделник - Петък: ${rawHours.replace(/.*:\s*/, "")}` : "Понеделник - Петък: 08:30 - 19:00 ч.",
    saturday: "Събота: 09:00 - 14:00 ч. (с предварителен час)",
    sunday: "Неделя & Празници: Почивен ден",
    note: "Спешни пациенти с остра болка се приемат с предимство след обаждане по телефона."
  };
}

export function getBusinessAddress(business: Business): string {
  if (business.address && business.address.trim() !== "") {
    return business.address;
  }
  return `гр. ${business.city}, централен район`;
}